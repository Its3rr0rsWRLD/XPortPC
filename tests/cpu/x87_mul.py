"""Compare native and translated FMUL forms of the x87 leaf-function profile: FMUL with m32 and m64
operands, FMUL ST(0), ST(i), FMUL ST(i), ST(0) and FMULP ST(i), ST(0).

Usage:
    python tests/cpu/x87_mul.py asm <asm> <def>             regenerate the MASM source and exports
    python tests/cpu/x87_mul.py emit <dll> <cpp> [control]   translate (and optionally mutate) the fixture
    python tests/cpu/x87_mul.py check <harness> <native> <lifted> [controls...]

The exports, harness and guards follow tests/cpu/x87_add.py, whose exact-rational helpers this check
reuses; the product model below is independent of tools/x87_soft.h.
"""
from fractions import Fraction
from pathlib import Path
import platform
import random
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tools"))
import x87_add as base  # noqa: E402  (tests/cpu is the script directory)
from x87_add import INDEFINITE, J, Q, classify, from_binary, m80, m80_bytes, round_format, to_binary  # noqa: E402

INPUT, OUTPUT = base.INPUT, base.OUTPUT

# name: (input kind, sequence). ("fmul_mem", kind, offset) is FMUL m32/m64 with an input operand,
# ("fmul_st0", i) is FMUL ST(0), ST(i), ("fmul_sti", i) is FMUL ST(i), ST(0) and ("fmulp", i) is FMULP.
SEQUENCES = {
    "mul_m80": ("pair80", [("fld", "m80", 0), ("fld", "m80", 16), ("fmulp", 1), ("fstp", "m80", 0)]),
    "mul_to_m64": ("pair80", [("fld", "m80", 0), ("fld", "m80", 16), ("fmulp", 1), ("fstp", "m64", 0)]),
    "mul_to_m32": ("pair80", [("fld", "m80", 0), ("fld", "m80", 16), ("fmulp", 1), ("fstp", "m32", 0)]),
    "mul_st0_sti": ("pair80", [("fld", "m80", 0), ("fld", "m80", 16), ("fmul_st0", 1), ("fstp", "m80", 0),
                               ("fstp", "m80", 16)]),
    "mul_sti_st0": ("pair80", [("fld", "m80", 0), ("fld", "m80", 16), ("fmul_sti", 1), ("fstp", "m80", 0),
                               ("fstp", "m80", 16)]),
    "mul_square": ("m80", [("fld", "m80", 0), ("fmul_st0", 0), ("fstp", "m80", 0)]),
    "mul_mem32": ("m80_f32", [("fld", "m80", 0), ("fmul_mem", "m32", 16), ("fstp", "m80", 0)]),
    "mul_mem64": ("m80_f64", [("fld", "m80", 0), ("fmul_mem", "m64", 16), ("fstp", "m80", 0)]),
    "mul_f32": ("pair32", [("fld", "m32", 0), ("fmul_mem", "m32", 4), ("fstp", "m32", 0)]),
    "mul_f64": ("pair64", [("fld", "m64", 0), ("fmul_mem", "m64", 8), ("fstp", "m64", 0)]),
    # (a * c) * b through FMULP ST(2), ST(0), and a * b + c with the product rounded before the add.
    "mul_three": ("triple80", [("fld", "m80", 0), ("fld", "m80", 16), ("fld", "m80", 32), ("fmulp", 2),
                               ("fmulp", 1), ("fstp", "m80", 0)]),
    "mul_add": ("triple80", [("fld", "m80", 0), ("fld", "m80", 16), ("fmulp", 1), ("fld", "m80", 32),
                             ("faddp", 1), ("fstp", "m80", 0)]),
}

PTR = base.PTR
SIZE = {"m32": 4, "m64": 8, "m80": 10}

# Source mutations of the generated C++ (the helper header is part of it). Each control must mismatch.
CONTROLS = {
    # The product rounds to 64 significand bits, as with precision control 64.
    "pc64": (base.ARITH, "x87_arith{64, 16383, 0x7ffe}"),
    # The product rounds in the binary64 exponent range, as host double arithmetic would.
    "double": (base.ARITH, "x87_arith{53, 1023, 0x7fe}"),
    # The low 64 bits of the 128-bit product are dropped before rounding.
    "nolow": (re.compile(r"x87_round\(sign, e, hi, lo, x87_arith"), "x87_round(sign, e, hi, 0, x87_arith"),
    # The product takes the sign of the first operand.
    "sign": (re.compile(r"const bool sign = x87_sign\(a\) != x87_sign\(b\);"), "const bool sign = x87_sign(a);"),
    # Infinity times zero gives infinity instead of the indefinite.
    "infzero": (re.compile(r"if \(\(ia && zb\) \|\| \(ib && za\)\) return x87_indefinite;"), ";"),
    # m32 and m64 operands are quieted before the NaN rules see them, as a plain load would.
    "memquiet": (re.compile(r"(x87_operand_f(?:32|64)\(uint(?:32|64)_t bits\) \{ return x87_from_binary\([^)]*), false\)"),
                 r"\1, true)"),
}


# ---- MASM generation -------------------------------------------------------------------------------

def asm_line(step):
    op, *args = step
    if op in ("fmulp", "faddp"):
        return f"    {op} st({args[0]}), st"
    if op == "fmul_st0":
        return f"    fmul st, st({args[0]})"
    if op == "fmul_sti":
        return f"    fmul st({args[0]}), st"
    if op == "fmul_mem":
        return f"    fmul {PTR[args[0]]} ptr [rcx+{args[1]}]"
    return base.asm_line(step)


def write_asm(asm_path, def_path):
    lines = ["; Generated by tests/cpu/x87_mul.py asm; edit SEQUENCES there and regenerate.",
             "; Source-owned differential fixture for the FMUL forms of the x87 leaf-function profile. Each export",
             "; reads an input block at RCX, writes an output block at RDX and returns with the x87 stack empty.",
             ".code", ""]
    for name, (_, steps) in SEQUENCES.items():
        lines += [f"{name} PROC FRAME", "    .endprolog", *(asm_line(s) for s in steps), "    ret", f"{name} ENDP", ""]
    lines.append("END")
    Path(asm_path).write_text("\n".join(lines) + "\n", encoding="ascii")
    Path(def_path).write_text("EXPORTS\n" + "".join(f"    {name}\n" for name in SEQUENCES), encoding="ascii")


# ---- Translation -----------------------------------------------------------------------------------

def emit(image, output, control="lifted"):
    import pefile
    from cpu_leaf_aot import export_rva
    from cpu_ranges import function_ranges
    from ffx_version_query import INTEGER_HEADER, lower, region
    from x87_lower import X87_HEADER

    parts = [INTEGER_HEADER, X87_HEADER]
    with pefile.PE(str(image), fast_load=True) as pe:
        for name in SEQUENCES:
            (bounds,) = function_ranges(pe, export_rva(pe, name))
            code = lower(region(pe, *bounds), ["rcx = a; rdx = b;"], {}, {}, {}, x87=True)
            parts.append(f'extern "C" __declspec(dllexport) word {name}(word a, word b) {{\n{code}\n}}\n')
    text = "".join(parts)
    if control != "lifted":
        expression, replacement = CONTROLS[control]
        text, count = expression.subn(replacement, text)
        if not count:
            raise AssertionError(f"control {control} changed nothing")
        print(f"control {control}: {count} replacements")
    output.write_text(text, encoding="ascii")


# ---- Independent model -----------------------------------------------------------------------------

def operand(kind, bits):
    """An m32 or m64 arithmetic operand: converted exactly, with a signaling NaN left signaling."""
    v = from_binary(kind, bits)
    precision, _, exp_bits = base.BINARY[kind]
    fb = precision - 1
    is_snan = (bits >> fb) & ((1 << exp_bits) - 1) == (1 << exp_bits) - 1 and bits & ((1 << fb) - 1) \
        and not bits >> (fb - 1) & 1
    return (v[0] & ~Q, v[1]) if is_snan else v


def nan_result(a, b):
    """SDM Vol. 1 Table 4-7 for two operands of which at least one is a NaN (the measured tie rule of
    tests/cpu/x87_add.py: equal significands give the positive NaN)."""
    na, nb = classify(a)[0] == "nan", classify(b)[0] == "nan"
    if na and nb:
        qa, qb = bool(a[0] & Q), bool(b[0] & Q)
        pick = (a if qa else b) if qa != qb else (b if (b[0], -(b[1] >> 15)) > (a[0], -(a[1] >> 15)) else a)
    else:
        pick = a if na else b
    return pick[0] | Q, pick[1]


def mul(a, b):
    """FMUL with control word 0x027F: the exact product rounded to 53 bits in the extended exponent range."""
    ca, cb = classify(a), classify(b)
    if "unsupported" in (ca[0], cb[0]):
        return INDEFINITE
    if "nan" in (ca[0], cb[0]):
        return nan_result(a, b)
    sign = ca[1] ^ cb[1]
    kinds = {ca[0], cb[0]}
    if kinds == {"inf", "zero"}:
        return INDEFINITE
    if "inf" in kinds:
        return J, sign << 15 | 0x7FFF
    if "zero" in kinds:
        return 0, sign << 15
    rounded = round_format(ca[2] * cb[2], 53, 16383, 0x7FFE)
    if rounded is None:
        return J, sign << 15 | 0x7FFF
    m, biased = rounded
    return m << 11, sign << 15 | biased


def reference(name, data):
    slots, out = [], bytearray(b"\xcc" * OUTPUT)

    def read(kind, offset):
        return int.from_bytes(data[offset:offset + SIZE[kind]], "little")

    for op, *args in SEQUENCES[name][1]:
        if op == "fld":
            raw = read(*args)
            slots.append((raw & (2 ** 64 - 1), raw >> 64) if args[0] == "m80" else from_binary(args[0], raw))
        elif op == "fstp":
            kind, offset = args
            v = slots.pop()
            encoded = v[0] | v[1] << 64 if kind == "m80" else to_binary(kind, v)
            out[offset:offset + SIZE[kind]] = encoded.to_bytes(SIZE[kind], "little")
        elif op == "fmul_mem":
            slots[-1] = mul(slots[-1], operand(args[0], read(*args)))
        elif op == "fmul_st0":
            slots[-1] = mul(slots[-1], slots[-1 - args[0]])
        elif op == "fmul_sti":
            slots[-1 - args[0]] = mul(slots[-1 - args[0]], slots[-1])
        else:
            k = len(slots) - 1 - args[0]
            slots[k] = (mul if op == "fmulp" else base.add)(slots[k], slots[-1])
            slots.pop()
    assert not slots
    return bytes(out)


# ---- Inputs ----------------------------------------------------------------------------------------

def pairs80():
    s = base.special_m80()
    rows = [(a, b) for a in s for b in s]
    one = (J, 0x3FFF)
    rng = random.Random(1024)
    for _ in range(120):  # 27-bit odd factors: a 54-bit product ending in 1, an exact halfway case
        x, y = (rng.getrandbits(26) | 1 << 26 | 1 for _ in range(2))
        if x * y >= 1 << 53:
            rows.append((m80(x, -26), m80(y if rng.random() < 0.5 else -y, -26)))
    rows += [
        (one, (J | 1 << 10, 0x3FFF)), (one, (J | 3 << 10, 0x3FFF)), (one, (J | 1 << 10 | 1, 0x3FFF)),  # x * 1
        (one, (J | 1, 0x3FFF)), ((J | 1 << 10, 0x3FFF), (J | 1, 0x3FFF)),
        (m80(1, 600), m80(1, 600)), (m80(3, 600), m80(-5, 500)), (m80(1, -600), m80(1, -600)),  # binary64 range
        (m80(1, -1022), m80(1, -53)), (m80(3, -1023), m80(1, -52)),
        (m80(1, 8000), m80(1, 8383)), (m80(1, 8191), m80(1, 8192)), ((0xFFFFFFFFFFFFF800, 0x7FFE), one),  # overflow
        ((0xFFFFFFFFFFFFF800, 0x7FFE), (J | 1 << 10 | 1, 0x3FFF)), ((0xFFFFFFFFFFFFF800, 0x7FFE), (J | 1 << 9, 0x3FFF)),
        (m80(1, -8000), m80(1, -8382)), (m80(1, -8000), m80(1, -8383)), (m80(1, -8191), m80(1, -8192)),  # underflow
        (m80(1, -16000), m80(1, -446)), (m80(3, -16000), m80(1, -447)), (m80(1, -16382), m80(1, -53)),
        (m80(1, -16382), m80(1, -52)), (m80(1, -16382), (J | 1 << 10, 0x3FFF - 52)), ((J - 1, 0), (J, 0x3FFF + 1)),
        ((J - 1, 0), (J | 1, 0x3FFF)), ((1, 0), (J, 0x3FFF + 63)), ((1, 0), (J, 0x3FFF + 62)), ((0x801, 0), one),
        ((J | 5, 0x7FFF), (J | 5, 0xFFFF)), ((J | 5, 0xFFFF), (J | 5, 0x7FFF)),               # NaN ties by sign
    ]
    # (2^63 + u)(2^63 + v) with u + v = 1024 (mod 2048): the high 64 bits of the doubled product sit exactly
    # halfway between 53-bit neighbours, and only the nonzero low 64 bits (2uv) decide the rounding.
    for u, v in ((1023, 1), (1022, 2), (1023 + 4096, 1), (1000, 24), (3071, 1), (2047 + 1024, 2048)):
        for ea, eb, sa in ((0x3FFF, 0x3FFF, 0), (0x3FFF, 0x3FFF, 0x8000), (0x4100, 0x3E00, 0), (1, 0x3FFF + 70, 0)):
            rows.append(((J | u, ea | sa), (J | v, eb)))
    for _ in range(600):
        a = (J | rng.getrandbits(63), rng.randint(0x3FFF - 200, 0x3FFF + 200) | rng.choice((0, 0x8000)))
        b = (J | rng.getrandbits(63), rng.randint(0x3FFF - 200, 0x3FFF + 200) | rng.choice((0, 0x8000)))
        rows.append((a, b))
    for _ in range(200):  # products near the extended underflow and overflow thresholds
        low = rng.random() < 0.5
        ea = rng.randint(1, 0x3FFF - 100) if low else rng.randint(0x3FFF + 100, 0x7FFE)
        target = rng.randint(-80, 5) if low else rng.randint(0x7FFE - 3, 0x7FFE + 3)
        eb = target - ea + 0x3FFF
        if 1 <= eb <= 0x7FFE:
            rows.append(((J | rng.getrandbits(63), ea), (J | rng.getrandbits(63), eb | rng.choice((0, 0x8000)))))
    return rows


def cases():
    f64, f32 = base.f64_bits(), base.f32_bits()
    specials = base.special_m80()
    rng = random.Random(5)
    pairs = pairs80()

    def random_m80():
        return J | rng.getrandbits(63), rng.randint(0x3FFF - 300, 0x3FFF + 300) | rng.choice((0, 0x8000))

    def m80_block(*values):
        return b"".join(m80_bytes(v) for v in values)

    blocks = {
        "pair80": [m80_block(a, b) for a, b in pairs],
        "m80": [m80_bytes(v) for v in base.m80_singles()] + [m80_bytes(random_m80()) for _ in range(200)],
        "m80_f32": [m80_bytes(v) + b.to_bytes(4, "little") for v in specials for b in f32[:17]]
                   + [m80_bytes(random_m80()) + rng.getrandbits(32).to_bytes(4, "little") for _ in range(300)],
        "m80_f64": [m80_bytes(v) + b.to_bytes(8, "little") for v in specials for b in f64[:18]]
                   + [m80_bytes(random_m80()) + rng.getrandbits(64).to_bytes(8, "little") for _ in range(300)],
        "pair32": [a.to_bytes(4, "little") + b.to_bytes(4, "little") for a in f32[:17] for b in f32[:17]]
                  + [rng.getrandbits(32).to_bytes(4, "little") + rng.getrandbits(32).to_bytes(4, "little")
                     for _ in range(300)],
        "pair64": [a.to_bytes(8, "little") + b.to_bytes(8, "little") for a in f64[:18] for b in f64[:18]]
                  + [rng.getrandbits(64).to_bytes(8, "little") + rng.getrandbits(64).to_bytes(8, "little")
                     for _ in range(300)],
        "triple80": [m80_block(*rng.sample(specials, 3)) for _ in range(200)]
                    + [m80_block(random_m80(), random_m80(), random_m80()) for _ in range(300)],
    }
    for name, (kind, _) in SEQUENCES.items():
        for block in blocks[kind]:
            yield name, block.ljust(INPUT, b"\0")


# ---- Check -----------------------------------------------------------------------------------------

def check(harness_path, native_path, lifted_path, *control_paths):
    expected = [(name, data, reference(name, data)) for name, data in cases()]
    for label, path in (("native", native_path), ("lifted", lifted_path)):
        run = base.Runner(harness_path, path)
        bad = 0
        for name, data, want in expected:
            got, state = run(name, data)
            if not base.entry_state_ok(state):
                raise AssertionError(f"{label} {name} left state {state:#014x}; the profile requires control "
                                     "0x027f and an empty stack at TOP 0")
            if got != want:
                if not bad:
                    print(f"{label} first mismatch: {name}(input {data[:48].hex()})\n  got      {got[:16].hex()}\n"
                          f"  expected {want[:16].hex()}")
                bad += 1
        if bad:
            raise AssertionError(f"{label}: {bad}/{len(expected)} mismatches")
    print(f"{len(expected)} cases over {len(SEQUENCES)} exports (output block and guards) matched the reference "
          "in native and translated DLLs; each export returned with control 0x027f and an empty stack")
    print(f"processor: {platform.processor()}")
    first = {}
    for name, data, want in expected:
        first.setdefault(name, (data, want))
    for label, path in (("native", native_path), ("lifted", lifted_path)):
        run = base.Runner(harness_path, path)
        failed = [name for name, (data, want) in first.items() if not base.preserved(run, "x87_call", name, data, want)]
        if failed:
            raise AssertionError(f"x87_call lost a live caller value or control word around {label} {failed}")
    print(f"x87_call kept a live caller ST(0) value and control word around all {len(first)} native and "
          "translated exports")
    for path in control_paths:
        control = Path(path).stem.rsplit("_", 1)[-1]
        run = base.Runner(harness_path, path)
        bad = sum(1 for name, data, want in expected if run(name, data)[0] != want)
        print(f"control {control}: {bad}/{len(expected)} mismatches")
        if not bad:
            raise AssertionError(f"control {control} matched every case")
    check_rejections()


def check_rejections():
    from iced_x86 import Decoder
    from ffx_version_query import lower

    def attempt(hex_bytes):
        body = list(Decoder(64, bytes.fromhex(hex_bytes), ip=0x1000))
        try:
            lower(body, [], {}, {}, {}, x87=True)
        except ValueError as exc:
            return str(exc)
        return None

    fld, fstp = "db 29", "db 3a"  # fld tbyte ptr [rcx]; fstp tbyte ptr [rdx]
    rejected = {
        "fmulp st(0), st": (attempt(f"{fld} {fld} de c8 {fstp} {fstp} c3"), "unsupported x87 operation"),
        "fmul m32 on an empty stack": (attempt(f"d8 09 {fld} {fstp} c3"), "x87 stack underflow"),
        "fmul st, st(1) with one value": (attempt(f"{fld} d8 c9 {fstp} c3"), "x87 stack underflow"),
        "fmul st(2), st with two values": (attempt(f"{fld} {fld} dc ca {fstp} {fstp} c3"), "x87 stack underflow"),
        "fmulp with one value": (attempt(f"{fld} de c9 {fstp} c3"), "x87 stack underflow"),
        "fimul m32": (attempt(f"{fld} da 09 {fstp} c3"), "unsupported x87 operation"),
        "fimul m16": (attempt(f"{fld} de 09 {fstp} c3"), "unsupported x87 operation"),
        "fcomp st(1)": (attempt(f"{fld} {fld} d8 d9 {fstp} c3"), "unsupported x87 operation"),
        "fiadd m32": (attempt(f"{fld} da 01 {fstp} c3"), "unsupported x87 operation"),
    }
    for case, (message, needle) in rejected.items():
        if message is None or needle not in message:
            raise AssertionError(f"{case}: expected a rejection containing {needle!r}, got {message!r}")
    print(f"rejected {len(rejected)} sequences outside the profile: " + "; ".join(rejected))


if __name__ == "__main__":
    mode, first, second, *rest = sys.argv[1:]
    if mode == "asm":
        write_asm(first, second)
    elif mode == "emit":
        emit(Path(first), Path(second), *rest)
    elif mode == "check":
        check(first, second, *rest)
    else:
        raise ValueError(mode)
