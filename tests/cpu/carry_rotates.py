"""Compare native and translated RCL, RCR, CLC, STC and CMC (8-, 16-, 32- and 64-bit, register and memory)."""
import ctypes
from pathlib import Path
import re
import sys

import pefile

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tools"))
from cpu_leaf_aot import export_rva
from cpu_ranges import function_ranges
from ffx_version_query import INTEGER_HEADER, lower, region

U64 = ctypes.c_uint64
MASK64 = (1 << 64) - 1

# Destination: (MASM operand, width in bits, bit position within RAX or the memory qword, memory?)
DESTINATIONS = {
    "al": ("al", 8, 0, False), "ah": ("ah", 8, 8, False), "ax": ("ax", 16, 0, False),
    "eax": ("eax", 32, 0, False), "rax": ("rax", 64, 0, False),
    "m8": ("byte ptr [r9+8]", 8, 0, True), "m16": ("word ptr [r9+8]", 16, 0, True),
    "m32": ("dword ptr [r9+8]", 32, 0, True), "m64": ("qword ptr [r9+8]", 64, 0, True),
}
IMMEDIATES = (0, 5, 9, 17, 33, 65)
IMMEDIATE_DESTINATIONS = ("al", "ax", "eax", "rax", "m32")

# (export, operation, destination, count form): the count form is "1", "cl" or an immediate.
ROTATES = tuple(
    (f"{op}_{dest}_{form}", op, dest, form)
    for op in ("rcl", "rcr")
    for dest in DESTINATIONS
    for form in ("1", "cl", *(str(n) for n in IMMEDIATES if dest in IMMEDIATE_DESTINATIONS))
)
# (export, MASM lines): carry-flag instructions alone, and the multiword shifts RCL and RCR exist for.
FLAG_OPS = (
    ("clc_only", ("clc",)), ("stc_only", ("stc",)), ("cmc_only", ("cmc",)),
    ("stc_cmc", ("stc", "cmc")),
    ("shl128", ("mov rdx, qword ptr [r9+8]", "shl rax, 1", "rcl rdx, 1", "mov qword ptr [r9+8], rdx")),
    ("shr128", ("mov rdx, qword ptr [r9+8]", "shr rdx, 1", "rcr rax, 1", "mov qword ptr [r9+8], rdx")),
)
EXPORTS = tuple(name for name, *_ in ROTATES) + tuple(name for name, _ in FLAG_OPS)

# Source mutations of the generated C++. Each control DLL must disagree with the reference somewhere.
CONTROLS = {
    # The count masks to five bits (six for 64-bit) before it rotates.
    "nomask": (re.compile(r" & (31|63)u\)"), " & 255u)"),
    # Feeding the bit rotated out back in instead of CF turns RCL and RCR into ROL and ROR. Only the uintN_t(c)
    # casts of the rotate loops: the shared prelude's fma_x86 also has a "(c)".
    "nocarry": (re.compile(r"(int(?:8|16|32|64)_t)\(c\)"), r"\1(out)"),
    # STC sets CF.
    "stc": (re.compile(r"carry = true;"), "carry = false;"),
}

VALUES = (0, 1, 0x7f, 0x80, 0xff, 0x8000, 0xffff, 0x80000000, 0xffffffff, 0x8000000000000000,
          MASK64, 0x0123456789abcdef, 0xfedcba9876543210, 0xdeadbeef00c0ffee)
COUNTS = (*range(0, 71), 96, 128, 255)
# add r8, r8 presets (ZF, CF): 0 -> (1, 0), 1 -> (0, 0), 1 << 63 -> (1, 1), 3 << 62 -> (0, 1).
PRESETS = (0, 1, 1 << 63, 3 << 62)


def asm():
    """The MASM source of tests/cpu/carry_rotates.asm."""
    out = ["""; Source-owned differential fixture for RCL, RCR, CLC, STC and CMC. Generated by
; tests/cpu/carry_rotates.py asm. Each export takes (value, count, preset, state). It copies the value to
; RAX and to state[1], the count to RCX and sets ZF and CF with add r8, r8. It returns RAX and writes
; (CF << 1) | ZF to state[0]; memory forms rotate state[1] in place.
.code

ROTATE_ENTER MACRO
    mov rax, rcx
    mov rcx, rdx
    mov qword ptr [r9+8], rax
    add r8, r8
ENDM

ROTATE_LEAVE MACRO
    LOCAL no_carry, no_zero
    mov r10d, 0
    jae short no_carry
    mov r10d, 2
no_carry:
    jne short no_zero
    or r10d, 1
no_zero:
    mov qword ptr [r9], r10
    ret
ENDM
"""]
    bodies = [(name, (f"{op} {DESTINATIONS[dest][0]}, {form}",)) for name, op, dest, form in ROTATES]
    for name, lines in bodies + list(FLAG_OPS):
        out.append("\n".join([f"{name} PROC FRAME", "    .endprolog", "    ROTATE_ENTER",
                              *(f"    {line}" for line in lines), "    ROTATE_LEAVE", f"{name} ENDP", ""]))
    out.append("END\n")
    return "\n".join(out)


def emit(image, output, control="lifted"):
    parts = [INTEGER_HEADER]
    with pefile.PE(str(image), fast_load=True) as pe:
        for name in EXPORTS:
            (bounds,) = function_ranges(pe, export_rva(pe, name))
            code = lower(region(pe, *bounds), ["rcx = a; rdx = b; r8 = c; r9 = state;"], {}, {}, {})
            parts.append(f'extern "C" __declspec(dllexport) word {name}(word a, word b, word c, word state) {{\n{code}\n}}\n')
    text = "".join(parts)
    if control != "lifted":
        expression, replacement = CONTROLS[control]
        text, count = expression.subn(replacement, text)
        if not count:
            raise AssertionError(f"control {control} changed nothing")
        print(f"control {control}: {count} replacements")
    output.write_text(text, encoding="ascii")


def rotate(op, value, bits, count, carry):
    """Intel SDM RCL/RCR pseudocode: mask the count, reduce 8- and 16-bit counts, then step bit by bit."""
    steps = count & (0x3f if bits == 64 else 0x1f)
    if bits < 32:
        steps %= bits + 1
    top = 1 << (bits - 1)
    for _ in range(steps):
        if op == "rcl":
            out = (value & top) != 0
            value = ((value << 1) | carry) & ((1 << bits) - 1)
        else:
            out = value & 1
            value = (value >> 1) | (top if carry else 0)
        carry = int(out)
    return value, carry


def merge(base, value, bits, position):
    mask = ((1 << bits) - 1) << position
    return (base & ~mask) | (value << position)


def reference(name, value, count, preset):
    """(return RAX, state[0] flags, state[1]) expected for one call."""
    total = (preset + preset) & MASK64
    zf, cf = int(total == 0), int(preset + preset > MASK64)
    rax, memory = value, value
    rotates = {row[0]: row for row in ROTATES}
    if name in rotates:
        _, op, dest, form = rotates[name]
        _, bits, position, in_memory = DESTINATIONS[dest]
        steps = count if form == "cl" else int(form)
        if in_memory:
            v, cf = rotate(op, memory & ((1 << bits) - 1), bits, steps, cf)
            memory = merge(memory, v, bits, 0)
        else:
            v, cf = rotate(op, (rax >> position) & ((1 << bits) - 1), bits, steps, cf)
            rax = v if bits == 32 else merge(rax, v, bits, position)  # a 32-bit write zero-extends
    elif name in ("clc_only", "stc_only", "cmc_only", "stc_cmc"):
        cf = {"clc_only": 0, "stc_only": 1, "cmc_only": 1 - cf, "stc_cmc": 0}[name]
    else:  # shl128 and shr128 on the 128-bit value high:low = value:value; SHL and SHR set ZF, RCL and RCR keep it
        if name == "shl128":
            cf, rax = rax >> 63, (rax << 1) & MASK64
            zf = int(rax == 0)
            memory, cf = rotate("rcl", memory, 64, 1, cf)
        else:
            cf, memory = memory & 1, memory >> 1
            zf = int(memory == 0)
            rax, cf = rotate("rcr", rax, 64, 1, cf)
    return rax, cf << 1 | zf, memory


def load_lib(path):
    lib = ctypes.CDLL(str(Path(path).resolve()))
    for name in EXPORTS:
        fn = getattr(lib, name)
        fn.argtypes, fn.restype = [U64, U64, U64, ctypes.POINTER(U64 * 2)], U64
    return lib


def cases():
    counted = {name for name, op, dest, form in ROTATES if form == "cl"}
    for name in EXPORTS:
        for value in VALUES:
            for count in (COUNTS if name in counted else (0, 3)):
                for preset in PRESETS:
                    yield name, (value, count, preset), reference(name, value, count, preset)


def mismatches(lib, expected):
    state = (U64 * 2)()
    found = []
    for name, (value, count, preset), want in expected:
        state[0], state[1] = 0xdeadbeef, 0xdeadbeef
        rax = getattr(lib, name)(value, count, preset, ctypes.byref(state))
        if (rax, state[0], state[1]) != want:
            found.append((name, (value, count, preset), want, (rax, state[0], state[1])))
    return found


def check(native_path, lifted_path, *control_paths):
    expected = list(cases())
    for label, path in (("native", native_path), ("lifted", lifted_path)):
        bad = mismatches(load_lib(path), expected)
        if bad:
            name, args, want, got = bad[0]
            raise AssertionError(f"{label}: {len(bad)} mismatches; first {name}{tuple(hex(a) for a in args)} = "
                                 f"{tuple(hex(g) for g in got)}, expected {tuple(hex(w) for w in want)}")
    print(f"{len(expected)} cases over {len(EXPORTS)} exports (RAX, memory, ZF/CF) matched the reference "
          "in native and translated DLLs")
    for path in control_paths:
        control = Path(path).stem.rsplit("_", 1)[-1]
        bad = mismatches(load_lib(path), expected)
        print(f"control {control}: {len(bad)}/{len(expected)} mismatches")
        if not bad:
            raise AssertionError(f"control {control} matched every case")


if __name__ == "__main__":
    mode, *args = sys.argv[1:]
    if mode == "asm":  # regenerate tests/cpu/carry_rotates.asm and .def
        Path(args[0]).write_text(asm(), encoding="utf-8", newline="\n")
        Path(args[1]).write_text("EXPORTS\n" + "".join(f"    {name}\n" for name in EXPORTS), encoding="utf-8", newline="\n")
    elif mode == "emit":
        emit(Path(args[0]), Path(args[1]), *args[2:])
    elif mode == "check":
        check(*args)
    else:
        raise ValueError(mode)
