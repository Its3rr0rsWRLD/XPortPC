"""Compare native and translated FXTRACT of the x87 leaf-function profile.

Usage:
    python tests/cpu/x87_xtract.py asm <asm> <def>             regenerate the MASM source and exports
    python tests/cpu/x87_xtract.py emit <dll> <cpp> [control]   translate (and optionally mutate) the fixture
    python tests/cpu/x87_xtract.py check <harness> <native> <lifted> [controls...]

The exports, harness and guards follow tests/cpu/x87_add.py, and the other steps use the format of
tests/cpu/x87_moves.py. emit checks that every decoded x87 instruction is the form its sequence names.
The model splits values with Fraction arithmetic and is independent of tools/x87_soft.h.
"""
from fractions import Fraction
from pathlib import Path
import platform
import random
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "tools"))
import x87_add as base  # noqa: E402  (tests/cpu is the script directory)
import x87_integers as integers  # noqa: E402
from x87_add import INDEFINITE, J, Q, classify, floor_log2, from_binary, m80_bytes, m80_exact, to_binary  # noqa: E402
from x87_div import SIZE  # noqa: E402

INPUT, OUTPUT = base.INPUT, base.OUTPUT

# ("fxtract",) is the new step; the others use the x87_moves and x87_integers formats. After FXTRACT,
# ST(0) is the significand and ST(1) the exponent.
SEQUENCES = {
    "xtract_m80": ("m80", [("fld", "m80", 0), ("fxtract",), ("fstp", "m80", 0), ("fstp", "m80", 16)]),
    "xtract_to_m64": ("m80", [("fld", "m80", 0), ("fxtract",), ("fstp", "m64", 0), ("fstp", "m64", 8)]),
    "xtract_to_m32": ("m80", [("fld", "m80", 0), ("fxtract",), ("fstp", "m32", 0), ("fstp", "m32", 4)]),
    "xtract_f64": ("f64", [("fld", "m64", 0), ("fxtract",), ("fstp", "m80", 0), ("fstp", "m80", 16)]),
    "xtract_f32": ("f32", [("fld", "m32", 0), ("fxtract",), ("fstp", "m80", 0), ("fstp", "m80", 16)]),
    # The significand split again (exponent +0 for a finite value), and exponent + significand.
    "xtract_twice": ("m80", [("fld", "m80", 0), ("fxtract",), ("fxtract",), ("fstp", "m80", 0), ("fstp", "m80", 16),
                             ("fstp", "m80", 32)]),
    "xtract_sum": ("m80", [("fld", "m80", 0), ("fxtract",), ("faddp", "pop", 1), ("fstp", "m80", 0)]),
    # The eighth register, then every value back out.
    "xtract_depth8": ("m64x7", [("fld", "m64", 8 * k) for k in range(7)] + [("fxtract",)]
                      + [("fstp", "m64", 8 * k) for k in range(8)]),
}

CONTROLS = {
    # A zero gives an exponent of +inf instead of -inf.
    "zeroexp": (re.compile(r"exponent = \{x87_integer_bit, 0xffff\}; return v; \}  // xtract zero"),
                "exponent = {x87_integer_bit, 0x7fff}; return v; }  // xtract zero"),
    # A denormal is split without normalizing it first.
    "denormal": (re.compile(r"const X87Unpacked u = x87_unpack\(v\);\r?\n    exponent = x87_from_integer"),
                 "const X87Unpacked u = {x87_sign(v), x87_exp(v) ? static_cast<int>(x87_exp(v)) - 16383 : -16382, "
                 "v.sig};\n    exponent = x87_from_integer"),
    # The exponent keeps its bias.
    "biased": (re.compile(r"exponent = x87_from_integer\(u\.e\);"), "exponent = x87_from_integer(u.e + 16383);"),
    # The significand loses the sign.
    "unsigned": (re.compile(r"return \{u\.sig, static_cast<uint16_t>\(\(u\.sign \? 0x8000 : 0\) \| 16383\)\};"),
                 "return {u.sig, static_cast<uint16_t>(16383)};"),
    # A signaling NaN is returned unquieted.
    "snan": (re.compile(r"if \(x87_is_nan\(v\)\) \{ exponent = x87_quiet\(v\); return exponent; \}"),
             "if (x87_is_nan(v)) { exponent = v; return v; }"),
    # The two results are pushed in the other order.
    "order": (re.compile(r"x87_slot\[(\d)\] = e; x87_slot\[(\d)\] = s;"), r"x87_slot[\1] = s; x87_slot[\2] = e;"),
}


# ---- MASM generation and decoding ------------------------------------------------------------------

def asm_line(step):
    return "    fxtract" if step[0] == "fxtract" else integers.asm_line(step)


def expected_form(step):
    return ("fxtract", "") if step[0] == "fxtract" else integers.expected_form(step)


def write_asm(asm_path, def_path):
    lines = ["; coverage: source cpu_aot_x87_xtract",
             "; Generated by tests/cpu/x87_xtract.py asm; edit SEQUENCES there and regenerate.",
             "; Source-owned differential fixture for FXTRACT in the x87 leaf-function profile. Each export",
             "; reads an input block at RCX, writes an output block at RDX and returns with the x87 stack empty.",
             ".code", ""]
    for name, (_, steps) in SEQUENCES.items():
        lines += [f"{name} PROC FRAME", "    .endprolog", *(asm_line(s) for s in steps), "    ret", f"{name} ENDP", ""]
    lines.append("END")
    Path(asm_path).write_text("\n".join(lines) + "\n", encoding="ascii")
    Path(def_path).write_text("EXPORTS\n" + "".join(f"    {name}\n" for name in SEQUENCES), encoding="ascii")


def emit(image, output, control="lifted"):
    import pefile
    from cpu_leaf_aot import export_rva
    from cpu_ranges import function_ranges
    from ffx_version_query import INTEGER_HEADER, lower, region
    from x87_lower import X87_HEADER, is_x87

    parts = [INTEGER_HEADER, X87_HEADER]
    with pefile.PE(str(image), fast_load=True) as pe:
        for name, (_, steps) in SEQUENCES.items():
            (bounds,) = function_ranges(pe, export_rva(pe, name))
            body = region(pe, *bounds)
            decoded = [integers.decoded_form(i) for i in body if is_x87(i)]
            wanted = [expected_form(s) for s in steps]
            if decoded != wanted:
                raise AssertionError(f"{name} assembled as {decoded}, expected {wanted}")
            code = lower(body, ["rcx = a; rdx = b;"], {}, {}, {}, x87=True)
            parts.append(f'extern "C" __declspec(dllexport) word {name}(word a, word b) {{\n{code}\n}}\n')
    text = "".join(parts)
    if control != "lifted":
        expression, replacement = CONTROLS[control]
        text, count = expression.subn(replacement, text)
        if not count:
            raise AssertionError(f"control {control} changed nothing")
        print(f"control {control}: {count} replacements")
    output.write_text(text, encoding="ascii")


# ---- Independent model -----------------------------------------------------------------------------

def xtract(v):
    """FXTRACT with control word 0x027F: (exponent, significand) of v."""
    c = classify(v)
    if c[0] == "unsupported":
        return INDEFINITE, INDEFINITE
    if c[0] == "nan":
        quiet = (v[0] | Q, v[1])
        return quiet, quiet
    if c[0] == "inf":
        return (J, 0x7FFF), v
    if c[0] == "zero":
        return (J, 0xFFFF), v
    e = floor_log2(c[2])
    exponent = (0, 0) if e == 0 else m80_exact(int(e < 0), Fraction(abs(e)))
    return exponent, m80_exact(c[1], c[2] / Fraction(2) ** e)


def add(a, b):
    return base.add(a, b)


def reference(name, data):
    slots, out = [], bytearray(b"\xcc" * OUTPUT)

    def read(kind, offset):
        return int.from_bytes(data[offset:offset + SIZE[kind]], "little")

    for op, *args in SEQUENCES[name][1]:
        if op == "fxtract":
            exponent, significand = xtract(slots[-1])
            slots[-1] = exponent
            slots.append(significand)
        elif op == "fld":
            raw = read(*args)
            slots.append((raw & (2 ** 64 - 1), raw >> 64) if args[0] == "m80" else from_binary(args[0], raw))
        elif op == "fstp":
            kind, offset = args
            v = slots.pop()
            encoded = v[0] | v[1] << 64 if kind == "m80" else to_binary(kind, v)
            out[offset:offset + SIZE[kind]] = encoded.to_bytes(SIZE[kind], "little")
        else:  # ("faddp", "pop", 1): ST(1) + ST(0), popped
            slots[-2] = add(slots[-2], slots[-1])
            slots.pop()
    assert not slots
    return bytes(out)


# ---- Inputs ----------------------------------------------------------------------------------------

def cases():
    rng = random.Random(83)
    m80 = list(base.m80_singles())
    for _ in range(400):  # random values over the whole exponent range
        m80.append((J | rng.getrandbits(63), rng.randint(1, 0x7FFE) | rng.choice((0, 0x8000))))
    for width in range(1, 65):  # exponent 0 with each leading-bit position: denormals, and at 64 bits
        for _ in range(2):    # pseudo-denormals
            m80.append((1 << (width - 1) | rng.getrandbits(width - 1), rng.choice((0, 0x8000))))
    for e in (-1, 1, 2, 63, 64, -64, -16382, 16383):  # small, power-of-two-boundary and extreme exponents
        for sig in (J, J | 1, 0xFFFFFFFFFFFFFFFF):
            m80.append((sig, (16383 + e) | rng.choice((0, 0x8000))))
    for _ in range(40):  # signaling NaNs
        m80.append((J | 1 + rng.getrandbits(61), 0x7FFF | rng.choice((0, 0x8000))))
    for _ in range(30):  # pseudo-denormals, unnormals, and pseudo-infinities and pseudo-NaNs
        sign = rng.choice((0, 0x8000))
        m80 += [(J | rng.getrandbits(63), sign), (rng.getrandbits(63), rng.randint(1, 0x7FFE) | sign),
                (rng.getrandbits(62) if rng.getrandbits(1) else 0, 0x7FFF | sign)]
    f64 = base.f64_bits() + [rng.getrandbits(64) for _ in range(300)]
    f32 = base.f32_bits() + [rng.getrandbits(32) for _ in range(300)]
    blocks = {
        "m80": [m80_bytes(v) for v in m80],
        "f64": [b.to_bytes(8, "little") for b in f64],
        "f32": [b.to_bytes(4, "little") for b in f32],
        "m64x7": [b"".join(rng.choice(f64).to_bytes(8, "little") for _ in range(7)) for _ in range(300)],
    }
    for name, (kind, _) in SEQUENCES.items():
        for block in blocks[kind]:
            yield name, block.ljust(INPUT, b"\0")


# ---- Check -----------------------------------------------------------------------------------------

def check(harness_path, native_path, lifted_path, *control_paths):
    expected = [(name, data, reference(name, data)) for name, data in cases()]
    for label, path in (("native", native_path), ("lifted", lifted_path)):
        run = base.Runner(harness_path, path)
        bad = 0
        for name, data, want in expected:
            got, state = run(name, data)
            if not base.entry_state_ok(state):
                raise AssertionError(f"{label} {name} left state {state:#014x}; the profile requires control "
                                     "0x027f and an empty stack at TOP 0")
            if got != want:
                if not bad:
                    print(f"{label} first mismatch: {name}(input {data[:48].hex()})\n  got      {got[:48].hex()}\n"
                          f"  expected {want[:48].hex()}")
                bad += 1
        if bad:
            raise AssertionError(f"{label}: {bad}/{len(expected)} mismatches")
    print(f"{len(expected)} cases over {len(SEQUENCES)} exports (output block and guards) matched the reference "
          "in native and translated DLLs; each export returned with control 0x027f and an empty stack")
    print(f"processor: {platform.processor()}")
    first = {}
    for name, data, want in expected:
        first.setdefault(name, (data, want))
    for label, path in (("native", native_path), ("lifted", lifted_path)):
        run = base.Runner(harness_path, path)
        failed = [name for name, (data, want) in first.items() if not base.preserved(run, "x87_call", name, data, want)]
        if failed:
            raise AssertionError(f"x87_call lost a live caller value or control word around {label} {failed}")
    print(f"x87_call kept a live caller ST(0) value and control word around all {len(first)} native and "
          "translated exports")
    for path in control_paths:
        control = Path(path).stem.rsplit("_", 1)[-1]
        run = base.Runner(harness_path, path)
        bad = sum(1 for name, data, want in expected if run(name, data)[0] != want)
        print(f"control {control}: {bad}/{len(expected)} mismatches")
        if not bad:
            raise AssertionError(f"control {control} matched every case")
    check_rejections()


def check_rejections():
    from iced_x86 import Decoder
    from ffx_version_query import lower

    def attempt(hex_bytes):
        body = list(Decoder(64, bytes.fromhex(hex_bytes), ip=0x1000))
        try:
            lower(body, [], {}, {}, {}, x87=True)
        except ValueError as exc:
            return str(exc)
        return None

    fld, fstp = "db 29", "db 3a"  # fld tbyte ptr [rcx]; fstp tbyte ptr [rdx]
    rejected = {
        "fxtract on an empty stack": (attempt("d9 f4 c3"), "x87 stack underflow"),
        "fxtract at depth 8": (attempt(f"{fld} " * 8 + "d9 f4 " + f"{fstp} " * 9 + "c3"), "x87 stack overflow"),
        "fxtract with one store": (attempt(f"{fld} d9 f4 {fstp} c3"), "x87 stack not empty at return"),
        "frstor": (attempt(f"dd 21 {fld} d9 f4 {fstp} {fstp} c3"), "unsupported x87 operation"),
        "fxrstor": (attempt(f"0f ae 09 {fld} d9 f4 {fstp} {fstp} c3"), "unsupported x87 operation"),
    }
    for case, (message, needle) in rejected.items():
        if message is None or needle not in message:
            raise AssertionError(f"{case}: expected a rejection containing {needle!r}, got {message!r}")
    print(f"rejected {len(rejected)} sequences outside the profile: " + "; ".join(rejected))


if __name__ == "__main__":
    mode, first, second, *rest = sys.argv[1:]
    if mode == "asm":
        write_asm(first, second)
    elif mode == "emit":
        emit(Path(first), Path(second), *rest)
    elif mode == "check":
        check(first, second, *rest)
    else:
        raise ValueError(mode)
