"""The gfx1013 compute programs of runtime rung R5 (tests/runtime/r5_*.s) and their LLVM-free decoding.

    r5_programs_check.py check [<llvm-mc> <llvm-objcopy>]
    r5_programs_check.py header <llvm-mc> <llvm-objcopy> <r5_programs.h>

As tests/runtime/r3_programs_check.py does for R3: the committed bytes in r5_programs.h, decoded by tools/gfx_text.py,
must give the source text line for line; the translator (tools/pso_translate.py --stage compute, with the entry
contract d3d12_xs::pipeline derives from r5_frames.cpp's container) must accept r5_cs and refuse r5_refused_cs with its
reason, and the HLSL must bind only what the shim fills. Given llvm-mc, the committed bytes must be what it assembles and
its disassembly must equal gfx_text.py's text, for the programs and for FORMS.
"""
from pathlib import Path
import re
import sys
import tempfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(HERE))
import gfx_text  # noqa: E402
import pso_translate  # noqa: E402
from r3_programs_check import assemble, llvm_text  # noqa: E402

PROGRAMS = {"r5_cs": "r5_cs.s", "r5_refused_cs": "r5_refused_cs.s"}
# The entry contract the shim derives from r5_frames.cpp's container: s2..s6 are root words (push words 0..4 in
# binding order), s7 the workgroup id x; workgroup 4x1x1, wave32, one local-id VGPR.
CS_ROLES = {"sgprs": {**{f"s{s}": f"user:{s - 2}" for s in range(2, 7)}, "s7": "group_id.x"},
            "numthreads": [4, 1, 1], "wave": 32, "local_ids": 1}
FORMS = [
    "s_movk_i32 s10, 0x80", "s_movk_i32 s14, 0xffff", "s_lshl_b32 s0, s7, 2", "v_add_nc_u32_e32 v1, s0, v0",
    "v_add_f32_e32 v4, v4, v6", "v_add_f32_e32 v10, s6, v4", "v_subrev_f32_e32 v8, s6, v4",
    "buffer_load_dwordx4 v[4:7], v2, s[8:11], 0 offen", "buffer_load_dwordx4 v[4:7], v2, s[8:11], 0 offen offset:16",
    "buffer_store_dwordx4 v[4:7], v2, s[8:11], 0 offen", "buffer_store_dwordx2 v[8:9], v3, s[12:15], 0 offen offset:80",
    "s_mov_b32 s11, 0x30000000", "s_barrier", "s_waitcnt vmcnt(0)",
]


def source_lines(name):
    lines = [line.split(";")[0].strip() for line in (HERE / PROGRAMS[name]).read_text(encoding="ascii").splitlines()]
    return [" ".join(line.split()) for line in lines if line]


def committed():
    text = (HERE / "r5_programs.h").read_text(encoding="ascii")
    out = {}
    for name in PROGRAMS:
        m = re.search(rf"{name}\[\] = \{{([^}}]*)\}};", text)
        if not m:
            raise AssertionError(f"r5_programs.h lacks {name}")
        out[name] = bytes(int(b, 16) for b in re.findall(r"0x([0-9a-f]{2})", m[1]))
    return out


def write_header(assembler, objcopy, path):
    with tempfile.TemporaryDirectory() as tmp:
        lines = ["// Generated by tests/runtime/r5_programs_check.py header (llvm-mc, -mcpu=gfx1013) from",
                 "// tests/runtime/r5_*.s. Do not edit.", "#pragma once", "#include <cstdint>", ""]
        for name in PROGRAMS:
            code = assemble(assembler, objcopy, source_lines(name), Path(tmp))
            lines.append(f"inline constexpr std::uint8_t {name}[] = {{{', '.join(f'0x{b:02x}' for b in code)}}};")
        Path(path).write_text("\n".join(lines) + "\n", encoding="ascii")


def check(assembler=None, objcopy=None):
    import pixel_aot
    programs = committed()
    for name, code in programs.items():
        decoded = [text for _, text in gfx_text.decode(code)]
        if decoded != source_lines(name):
            raise AssertionError(f"{name}: gfx_text.py decodes\n" + "\n".join(decoded))
        program = pixel_aot.name_branch_targets(gfx_text.decode(code), len(code))
        try:
            source, layout, refs = pso_translate.lower("compute", program, CS_ROLES)
            source = pso_translate.place_in_runtime_spaces(source, "compute", layout)
            assert refs == [], refs
        except ValueError as error:
            if name != "r5_refused_cs" or "A color export belongs to the pixel stage" not in str(error):
                raise
            print(f"{name}: refused as expected: {error}")
            continue
        if name == "r5_refused_cs":
            raise AssertionError("r5_refused_cs was translated")
        registers = sorted(set(re.findall(r"register\([^)]*\)", source)))
        expected = ["register(b1, space1000)", "register(b3, space1000)", "register(t2, space1000)",
                    "register(u0, space1000)", "register(u0, space1001)"]
        if registers != expected or "RootSignature" in source or "[numthreads(4, 1, 1)]" not in source:
            raise AssertionError(f"{name}: unexpected bindings {registers}")
        print(f"{name}: {len(program)} instructions decode to the source text and translate; bindings {registers}")
    # The contract is checked: a word past the push words and a missing workgroup size are refused.
    try:
        pso_translate.lower("compute", ["s_endpgm"], {**CS_ROLES, "numthreads": None})
    except ValueError as error:
        assert "workgroup size" in str(error), error
    else:
        raise AssertionError("a compute contract without a workgroup size was accepted")
    far = {**CS_ROLES, "sgprs": {"s2": "user:40"}}
    try:
        pso_translate.lower("compute", ["v_mov_b32_e32 v1, s2", "s_endpgm"], far)
    except ValueError as error:
        assert "push words" in str(error), error
    else:
        raise AssertionError("a read past the push words was accepted")
    if not assembler:
        print("llvm-mc not given: committed bytes and LLVM text comparison skipped")
        return 0
    with tempfile.TemporaryDirectory() as tmp:
        for name, code in programs.items():
            if assemble(assembler, objcopy, source_lines(name), Path(tmp)) != code:
                raise AssertionError(f"{name}: r5_programs.h differs from llvm-mc's assembly; regenerate it")
            if llvm_text(assembler, code) != source_lines(name):
                raise AssertionError(f"{name}: llvm-mc disassembles {llvm_text(assembler, code)}")
        for line in FORMS:
            code = assemble(assembler, objcopy, [line], Path(tmp))
            ours = [text for _, text in gfx_text.decode(code)]
            if ours != llvm_text(assembler, code):
                raise AssertionError(f"{line!r}: gfx_text.py {ours} != llvm-mc {llvm_text(assembler, code)}")
    print(f"llvm-mc agrees: {len(programs)} programs, {len(FORMS)} forms")
    return 0


if __name__ == "__main__":
    mode, *args = sys.argv[1:]
    if mode == "header":
        write_header(*args)
        sys.exit(0)
    sys.exit(check(*args))
