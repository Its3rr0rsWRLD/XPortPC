"""The gfx1013 programs of runtime rung R3 (tests/runtime/r3_*.s) and the LLVM-free disassembly the shim uses.

    r3_programs_check.py check [<llvm-mc> <llvm-objcopy>]
    r3_programs_check.py header <llvm-mc> <llvm-objcopy> <r3_programs.h>

The programs are assembled by llvm-mc 15 (`header`, run where LLVM 15 is installed) into tests/runtime/r3_programs.h,
which r3_triangle.cpp wraps in console containers. `check` needs no LLVM: every program's committed bytes, decoded by
tools/gfx_text.py, must give its source text line for line, and the translator must accept the triangle programs (with
the entry contract the shim derives from r3_triangle.cpp's containers) and refuse the control with its reason. Given
llvm-mc, it also requires that the committed bytes are what llvm-mc 15 assembles today, and that gfx_text.py's text
equals llvm-mc's disassembly for the programs and for FORMS, which covers every operand shape tools/gfx_text.py
corrects.
"""
from pathlib import Path
import re
import subprocess
import sys
import tempfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import gfx_text  # noqa: E402
import pso_translate  # noqa: E402

PROGRAMS = {"r3_vs": "r3_vs.s", "r3_ps": "r3_ps.s", "r3_refused_vs": "r3_refused_vs.s"}
# The entry contracts d3d12_xs::pipeline derives from r3_triangle.cpp's containers: s2..s5 are root words, assigned
# push words 0..3 in binding order; the pixel program's s2 is the interpolation base.
VS_ROLES = {"user_sgprs": {str(s): {"role": "inline", "word": s - 2} for s in range(2, 6)}}
PS_ROLES = {"sgprs": {"s2": "interp"}}
# Operand shapes gfx_text.py rewrites (waitcnt fields, a null SMEM offset, interpolation parameters) and their
# neighbours, compared with llvm-mc's disassembly when llvm-mc is given.
FORMS = [
    "s_load_dwordx4 s[8:11], s[4:5], 0x10", "s_load_dwordx4 s[8:11], s[4:5], null", "s_load_dword s8, s[4:5], null",
    "s_load_dwordx2 s[8:9], s[4:5], s6", "s_waitcnt vmcnt(1) lgkmcnt(2)", "s_waitcnt expcnt(0)",
    "s_waitcnt vmcnt(0) expcnt(1) lgkmcnt(3)", "s_waitcnt vmcnt(40)", "s_waitcnt lgkmcnt(0)", "s_waitcnt vmcnt(0)",
    "global_load_dwordx4 v[2:5], v1, s[2:3] offset:16", "global_load_dword v2, v[4:5], off",
    "global_load_dwordx2 v[2:3], v1, s[6:7]", "v_interp_mov_f32_e32 v2, p10, attr1.x",
    "v_interp_mov_f32_e32 v2, p20, attr1.y", "v_interp_mov_f32_e32 v7, p0, attr3.w", "s_mov_b32 m0, s2",
    "v_mov_b32_e32 v6, s8", "v_lshlrev_b32_e32 v1, 4, v0", "exp param0 v6, v7, v8, v9",
    "exp pos0 v2, v3, v4, v5 done vm", "exp mrt0 v2, v3, v4, v5 done vm", "s_endpgm",
]


def source_lines(name):
    lines = [line.split(";")[0].strip() for line in (HERE / PROGRAMS[name]).read_text(encoding="ascii").splitlines()]
    return [" ".join(line.split()) for line in lines if line]


def assemble(assembler, objcopy, lines, tmp):
    source, obj, binary = tmp / "p.s", tmp / "p.o", tmp / "p.bin"
    source.write_text("\n".join(lines) + "\n", encoding="ascii")
    subprocess.run([assembler, "-triple=amdgcn--amdpal", "-mcpu=gfx1013", "-filetype=obj", source, "-o", obj],
                   check=True)
    subprocess.run([objcopy, "-O", "binary", "--only-section=.text", obj, binary], check=True)
    return binary.read_bytes()


def llvm_text(assembler, code):
    result = subprocess.run([assembler, "--disassemble", "-triple=amdgcn--amdpal", "-mcpu=gfx1013"],
                            input=" ".join(f"0x{b:02x}" for b in code), capture_output=True, text=True, check=True)
    return [" ".join(line.split()) for line in result.stdout.splitlines() if line.strip() and ".text" not in line]


def committed():
    text = (HERE / "r3_programs.h").read_text(encoding="ascii")
    out = {}
    for name in PROGRAMS:
        m = re.search(rf"{name}\[\] = \{{([^}}]*)\}};", text)
        if not m:
            raise AssertionError(f"r3_programs.h lacks {name}")
        out[name] = bytes(int(b, 16) for b in re.findall(r"0x([0-9a-f]{2})", m[1]))
    return out


def write_header(assembler, objcopy, path):
    with tempfile.TemporaryDirectory() as tmp:
        lines = ["// Generated by tests/runtime/r3_programs_check.py header (llvm-mc 15, -mcpu=gfx1013) from",
                 "// tests/runtime/r3_*.s. Do not edit.", "#pragma once", "#include <cstdint>", ""]
        for name in PROGRAMS:
            code = assemble(assembler, objcopy, source_lines(name), Path(tmp))
            words = ", ".join(f"0x{b:02x}" for b in code)
            lines.append(f"inline constexpr std::uint8_t {name}[] = {{{words}}};")
        Path(path).write_text("\n".join(lines) + "\n", encoding="ascii")


def check(assembler=None, objcopy=None):
    import pixel_aot
    programs = committed()
    for name, code in programs.items():
        decoded = [text for _, text in gfx_text.decode(code)]
        if decoded != source_lines(name):
            raise AssertionError(f"{name}: gfx_text.py decodes\n" + "\n".join(decoded))
        program = pixel_aot.name_branch_targets(gfx_text.decode(code), len(code))
        stage = "pixel" if name == "r3_ps" else "vertex"
        roles = PS_ROLES if stage == "pixel" else VS_ROLES
        try:
            source, layout, _ = pso_translate.lower(stage, program, roles)
            pso_translate.place_in_runtime_spaces(source, stage, layout)
        except ValueError as error:
            if name != "r3_refused_vs" or "mrt0 is not a vertex-shader export" not in str(error):
                raise
            print(f"{name}: refused as expected: {error}")
            continue
        if name == "r3_refused_vs":
            raise AssertionError("r3_refused_vs was translated")
        print(f"{name}: {len(program)} instructions decode to the source text and translate")
    # Unverified instructions are refused by name.
    try:
        gfx_text.decode(bytes.fromhex("000080bf"))  # s_nop 0
    except ValueError as error:
        assert "s_nop" in str(error), error
    else:
        raise AssertionError("gfx_text.py decoded an instruction outside VERIFIED")
    if not assembler:
        print("llvm-mc not given: committed bytes and LLVM text comparison skipped")
        return 0
    with tempfile.TemporaryDirectory() as tmp:
        for name, code in programs.items():
            if assemble(assembler, objcopy, source_lines(name), Path(tmp)) != code:
                raise AssertionError(f"{name}: r3_programs.h differs from llvm-mc's assembly; regenerate it")
            if llvm_text(assembler, code) != source_lines(name):
                raise AssertionError(f"{name}: llvm-mc disassembles {llvm_text(assembler, code)}")
        for line in FORMS:
            code = assemble(assembler, objcopy, [line], Path(tmp))
            ours = [text for _, text in gfx_text.decode(code)]
            if ours != llvm_text(assembler, code):
                raise AssertionError(f"{line!r}: gfx_text.py {ours} != llvm-mc {llvm_text(assembler, code)}")
    print(f"llvm-mc agrees: {len(programs)} programs, {len(FORMS)} forms")
    return 0


if __name__ == "__main__":
    mode, *args = sys.argv[1:]
    if mode == "header":
        write_header(*args)
        sys.exit(0)
    sys.exit(check(*args))
