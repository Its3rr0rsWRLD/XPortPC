"""The gfx1013 programs of runtime rung R4b (tests/runtime/r4b_*.s): buffer V#s read from a descriptor table.

    r4b_programs_check.py check [<llvm-mc> <llvm-objcopy>]
    r4b_programs_check.py header <llvm-mc> <llvm-objcopy> <r4b_programs.h>

As tests/runtime/r4_programs_check.py: `header` assembles the programs into r4b_programs.h, which r4b_scene.cpp wraps
in console containers. `check` needs no LLVM: the committed bytes, decoded by tools/gfx_text.py, must give the source
text line for line; the translator must accept both programs under the entry contracts the shim derives from
r4b_scene.cpp's containers, report the descriptor-table reads the scene's table is laid out for (two vertex buffer
V#s, a stored typed pixel V#, four pixel constant slots) with their flags, bind title memory writable in both stages
(the pixel program stores; the vertex program is translated with the role the shim then gives it), and put the
descriptor words and constant slots in the runtime's registers. The forms the runtime still does not bind must be
refused with their reason. Given llvm-mc, the committed bytes must be its assembly, and gfx_text.py's text must equal
its disassembly on the programs and FORMS.
"""
from pathlib import Path
import re
import sys
import tempfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(HERE))
import gfx_text  # noqa: E402
import pso_translate  # noqa: E402
from r3_programs_check import assemble, llvm_text  # noqa: E402

PROGRAMS = {"r4b_vs": "r4b_vs.s", "r4b_ps": "r4b_ps.s"}
# The entry contracts d3d12_xs::pipeline derives from r4b_scene.cpp's containers. The pixel program stores, so the
# shim translates the vertex program ("memory ro" without the role) again with "title_memory": "rw".
VS_ROLES = {"user_sgprs": {"2": {"role": "base_vertex"}, "4": {"role": "descriptors", "set": 0}},
            "title_memory": "rw"}
PS_ROLES = {"sgprs": {"s2": "interp", "s3": "descriptors"}}
# (kind, slot or first descriptor word, set, byte offset, flags): the positions' V# at 0x00 and the colours' at 0x20
# (vertex words 0 and 4, untyped loads), the store target's V# at 0x40 (pixel word 64, typed and stored), constant
# slots 0..3 at 0x60..0xc0.
EXPECTED = {"r4b_vs": [("buffer", 0, 0, 0x00, 0), ("buffer", 4, 0, 0x20, 0)],
            "r4b_ps": [("constants", 0, 0, 0x60, 0), ("constants", 1, 0, 0x80, 0), ("constants", 2, 0, 0xa0, 0),
                       ("constants", 3, 0, 0xc0, 0), ("buffer", 64, 0, 0x40, 3)]}
REGISTERS = {
    "r4b_vs": ["cbuffer Descriptors : register(b4, space1000) { uint4 vsharp_words[32]; };",
               "RWByteAddressBuffer title_memory[8] : register(u0, space1001);"],
    "r4b_ps": ["cbuffer Descriptors : register(b4, space1000) { uint4 vsharp_words[32]; };",
               "RWByteAddressBuffer title_memory[8] : register(u0, space1001);",
               *(f"register(b{k}, space1003)" for k in range(4))],
}
# Forms the runtime does not bind, as one-line changes of a program, and the reason they give.
REFUSED = [
    ("r4b_vs", "buffer_load_dwordx4 v[4:7], v1, s[8:11], 0 idxen",
     ["buffer_load_format_d16_xyzw v[4:5], v1, s[8:11], 0 idxen"], "d16 typed vertex fetch"),
    ("r4b_vs", "exp param0 v8, v9, v10, v11",
     ["buffer_store_dword v8, v1, s[8:11], 0 idxen", "exp param0 v8, v9, v10, v11"], "memory side effects"),
    ("r4b_ps", "v_mov_b32_e32 v4, s44", ["s_mov_b32 s26, 0", "v_mov_b32_e32 v4, s44"],
     "not one descriptor-table V#"),
]
FORMS = [
    "buffer_load_dword v2, v1, s[8:11], 0 offen", "buffer_load_dword v2, v1, s[8:11], 0 idxen offset:12",
    "buffer_load_dwordx2 v[2:3], v1, s[8:11], 0 idxen", "buffer_load_dwordx4 v[4:7], v1, s[8:11], 0 idxen",
    "buffer_load_dwordx4 v[8:11], v1, s[12:15], 0 idxen offset:4", "buffer_store_dword v2, v1, s[8:11], 0 offen",
    "buffer_store_format_x v7, v6, s[24:27], 0 idxen", "buffer_store_format_x v7, v6, s[24:27], 0 idxen offset:8",
]


def source_lines(name):
    lines = [line.split(";")[0].strip() for line in (HERE / PROGRAMS[name]).read_text(encoding="ascii").splitlines()]
    return [" ".join(line.split()) for line in lines if line]


def committed():
    text = (HERE / "r4b_programs.h").read_text(encoding="ascii")
    out = {}
    for name in PROGRAMS:
        m = re.search(rf"{name}\[\] = \{{([^}}]*)\}};", text)
        if not m:
            raise AssertionError(f"r4b_programs.h lacks {name}")
        out[name] = bytes(int(b, 16) for b in re.findall(r"0x([0-9a-f]{2})", m[1]))
    return out


def write_header(assembler, objcopy, path):
    with tempfile.TemporaryDirectory() as tmp:
        lines = ["// Generated by tests/runtime/r4b_programs_check.py header (llvm-mc, -mcpu=gfx1013) from",
                 "// tests/runtime/r4b_*.s. Do not edit.", "#pragma once", "#include <cstdint>", ""]
        for name in PROGRAMS:
            code = assemble(assembler, objcopy, source_lines(name), Path(tmp))
            words = ", ".join(f"0x{b:02x}" for b in code)
            lines.append(f"inline constexpr std::uint8_t {name}[] = {{{words}}};")
        Path(path).write_text("\n".join(lines) + "\n", encoding="ascii")


def translate(name, program):
    stage = "pixel" if name.endswith("_ps") else "vertex"
    roles = PS_ROLES if stage == "pixel" else VS_ROLES
    source, layout, refs = pso_translate.lower(stage, program, roles)
    source, writes = pso_translate.writable_memory(source, roles)
    return pso_translate.place_in_runtime_spaces(source, stage, layout), refs, writes


def check(assembler=None, objcopy=None):
    import pixel_aot
    programs = committed()
    for name, code in programs.items():
        decoded = [text for _, text in gfx_text.decode(code)]
        if decoded != source_lines(name):
            raise AssertionError(f"{name}: gfx_text.py decodes\n" + "\n".join(decoded))
        program = pixel_aot.name_branch_targets(gfx_text.decode(code), len(code))
        source, refs, writes = translate(name, program)
        if refs != EXPECTED[name]:
            raise AssertionError(f"{name}: descriptor-table reads {refs}, expected {EXPECTED[name]}")
        if not writes:
            raise AssertionError(f"{name}: title memory is not bound writable")
        for text in REGISTERS[name]:
            if text not in source:
                raise AssertionError(f"{name}: the translation lacks {text!r}")
        if "CountedTitleLookup(title_ranges" not in source:
            raise AssertionError(f"{name}: title-memory accesses do not count TitleLookup misses")
        if "memory rw\n" not in pso_translate.bindings_text(refs, writes):
            raise AssertionError(f"{name}: the bindings do not say the program writes title memory")
        print(f"{name}: {len(program)} instructions decode to the source text and translate; reads {refs}")
    # Without the shim's role the vertex program reads title memory through SRVs, and says nothing about writes.
    program = pixel_aot.name_branch_targets(gfx_text.decode(programs["r4b_vs"]), len(programs["r4b_vs"]))
    source, _, refs = pso_translate.lower("vertex", program, {"user_sgprs": VS_ROLES["user_sgprs"]})
    source, writes = pso_translate.writable_memory(source, {})
    reads = pso_translate.READ_ONLY_MEMORY in source
    if writes or not reads or "memory ro\n" not in pso_translate.bindings_text(refs, writes, reads):
        raise AssertionError("r4b_vs: without the role title memory is not read-only, or the bindings do not say so")
    for name, line, replacement, reason in REFUSED:
        program = source_lines(name)
        at = program.index(line)
        changed = program[:at] + replacement + program[at + 1:]
        try:
            translate(name, changed)
        except ValueError as error:
            if reason not in str(error):
                raise AssertionError(f"{name} with {replacement}: refused for another reason: {error}")
            print(f"{name} with {replacement[0]!r}: refused as expected: {error}")
        else:
            raise AssertionError(f"{name} with {replacement}: translated")
    if not assembler:
        print("llvm-mc not given: committed bytes and LLVM text comparison skipped")
        return 0
    with tempfile.TemporaryDirectory() as tmp:
        for name, code in programs.items():
            if assemble(assembler, objcopy, source_lines(name), Path(tmp)) != code:
                raise AssertionError(f"{name}: r4b_programs.h differs from llvm-mc's assembly; regenerate it")
            if llvm_text(assembler, code) != source_lines(name):
                raise AssertionError(f"{name}: llvm-mc disassembles {llvm_text(assembler, code)}")
        for line in FORMS:
            code = assemble(assembler, objcopy, [line], Path(tmp))
            ours = [text for _, text in gfx_text.decode(code)]
            if ours != llvm_text(assembler, code) or ours != [line]:
                raise AssertionError(f"{line!r}: gfx_text.py {ours} != llvm-mc {llvm_text(assembler, code)}")
    print(f"llvm-mc agrees: {len(programs)} programs, {len(FORMS)} forms")
    return 0


if __name__ == "__main__":
    mode, *args = sys.argv[1:]
    if mode == "header":
        write_header(*args)
        sys.exit(0)
    sys.exit(check(*args))
