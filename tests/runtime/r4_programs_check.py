"""The gfx1013 programs of runtime rung R4 (tests/runtime/r4_*.s) and the LLVM-free disassembly the shim uses.

    r4_programs_check.py check [<llvm-mc> <llvm-objcopy>]
    r4_programs_check.py header <llvm-mc> <llvm-objcopy> <r4_programs.h>

As tests/runtime/r3_programs_check.py: `header` assembles the programs with llvm-mc 15 into r4_programs.h, which
r4_scene.cpp wraps in console containers. `check` needs no LLVM: the committed bytes, decoded by tools/gfx_text.py,
must give the source text line for line; the translator must accept both programs under the entry contracts the
shim derives from r4_scene.cpp's containers and report the descriptor-table reads the scene's heaps are laid out
for; and the forms the runtime does not bind must be refused with their reason. Given llvm-mc, the committed bytes
must be llvm-mc 15's assembly, and gfx_text.py's text must equal llvm-mc's disassembly on the programs and FORMS
(every R4 mnemonic, and the operand shapes gfx_text.py rewrites for them).
"""
from pathlib import Path
import re
import sys
import tempfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(HERE))
import gfx_text  # noqa: E402
import pso_translate  # noqa: E402
from r3_programs_check import assemble, llvm_text  # noqa: E402

PROGRAMS = {"r4_vs": "r4_vs.s", "r4_ps": "r4_ps.s"}
# The entry contracts d3d12_xs::pipeline derives from r4_scene.cpp's containers: root words become push words in
# binding order across the pipeline (vertex s2, s3, s8, s9 -> 0..3, pixel s5 -> 4), tables become sets in binding
# order per stage.
VS_ROLES = {"user_sgprs": {"2": {"role": "inline", "word": 0}, "3": {"role": "inline", "word": 1},
                           "4": {"role": "base_vertex"}, "5": {"role": "start_instance"},
                           "6": {"role": "descriptors", "set": 0},
                           "8": {"role": "inline", "word": 2}, "9": {"role": "inline", "word": 3}}}
PS_ROLES = {"sgprs": {"s2": "interp", "s3": "descriptors", "s4": "descriptors.1", "s5": "push:4"}}
# Descriptor-table reads (kind, slot, set, byte offset): the scene's per-draw CBV/SRV/UAV table holds the vertex
# constants at 0x00, the texture at 0x20 and the pixel constants at 0x40; its sampler table the sampler at 0.
EXPECTED = {"r4_vs": [("constants", 0, 0, 0)],
            "r4_ps": [("texture", 0, 0, 0x20), ("sampler", 0, 1, 0), ("constants", 0, 0, 0x40)]}
# Forms the runtime does not bind yet, as one-line changes of the pixel or vertex program, and the reason they give.
REFUSED = [
    ("r4_ps", "s_mov_b32 s22, s4", ["s_mov_b32 s22, s6"], "does not bind as a descriptor table"),
    ("r4_vs", "s_buffer_load_dwordx2 s[16:17], s[12:15], null", ["buffer_load_dwordx2 v[16:17], v1, s[12:15], 0 offen"],
     "b4 descriptor words"),
]
FORMS = [
    "s_mov_b64 s[50:51], exec", "s_mov_b64 exec, s[4:5]", "s_wqm_b64 exec, exec", "s_and_b64 exec, exec, s[50:51]",
    "s_and_b64 vcc, s[2:3], exec", "s_movk_i32 s21, 0x8000", "s_movk_i32 s7, 0x1234",
    "s_load_dwordx8 s[24:31], s[20:21], 0x20", "s_load_dwordx8 s[24:31], s[20:21], null",
    "s_buffer_load_dword s16, s[12:15], null", "s_buffer_load_dword s16, s[12:15], 0x14",
    "s_buffer_load_dwordx2 s[16:17], s[12:15], null", "s_buffer_load_dwordx4 s[40:43], s[36:39], 0x10",
    "v_add_nc_u32_e32 v1, s4, v0", "v_add_nc_u32_e32 v1, v2, v0", "v_add_f32_e32 v4, s16, v4",
    "v_mul_f32_e32 v12, s40, v12", "v_mul_f32_e32 v12, 0.5, v12", "v_mov_b32_e32 v9, 1.0",
    "v_interp_p1_f32_e32 v8, v0, attr0.x", "v_interp_p2_f32_e32 v9, v1, attr2.w",
    "image_sample v[12:15], v[8:9], s[24:31], s[32:35] dmask:0xf dim:SQ_RSRC_IMG_2D",
    "image_sample v[12:13], v[8:9], s[24:31], s[32:35] dmask:0x3 dim:SQ_RSRC_IMG_2D",
]


def source_lines(name):
    lines = [line.split(";")[0].strip() for line in (HERE / PROGRAMS[name]).read_text(encoding="ascii").splitlines()]
    return [" ".join(line.split()) for line in lines if line]


def committed():
    text = (HERE / "r4_programs.h").read_text(encoding="ascii")
    out = {}
    for name in PROGRAMS:
        m = re.search(rf"{name}\[\] = \{{([^}}]*)\}};", text)
        if not m:
            raise AssertionError(f"r4_programs.h lacks {name}")
        out[name] = bytes(int(b, 16) for b in re.findall(r"0x([0-9a-f]{2})", m[1]))
    return out


def write_header(assembler, objcopy, path):
    with tempfile.TemporaryDirectory() as tmp:
        lines = ["// Generated by tests/runtime/r4_programs_check.py header (llvm-mc 15, -mcpu=gfx1013) from",
                 "// tests/runtime/r4_*.s. Do not edit.", "#pragma once", "#include <cstdint>", ""]
        for name in PROGRAMS:
            code = assemble(assembler, objcopy, source_lines(name), Path(tmp))
            words = ", ".join(f"0x{b:02x}" for b in code)
            lines.append(f"inline constexpr std::uint8_t {name}[] = {{{words}}};")
        Path(path).write_text("\n".join(lines) + "\n", encoding="ascii")


def translate(name, program):
    stage = "pixel" if name.endswith("_ps") else "vertex"
    source, layout, refs = pso_translate.lower(stage, program, PS_ROLES if stage == "pixel" else VS_ROLES)
    return pso_translate.place_in_runtime_spaces(source, stage, layout), refs


def check(assembler=None, objcopy=None):
    import pixel_aot
    programs = committed()
    for name, code in programs.items():
        decoded = [text for _, text in gfx_text.decode(code)]
        if decoded != source_lines(name):
            raise AssertionError(f"{name}: gfx_text.py decodes\n" + "\n".join(decoded))
        program = pixel_aot.name_branch_targets(gfx_text.decode(code), len(code))
        source, refs = translate(name, program)
        if refs != EXPECTED[name]:
            raise AssertionError(f"{name}: descriptor-table reads {refs}, expected {EXPECTED[name]}")
        if name == "r4_vs" and "CountedTitleLookup(title_ranges" not in source:
            raise AssertionError("r4_vs: title-memory loads do not count TitleLookup misses")
        print(f"{name}: {len(program)} instructions decode to the source text and translate; reads {refs}")
    # An inline (immutable) sampler (rung R6): the S# words the program sets with s_mov become an inline_sampler
    # read the shim decodes, in place of the sampler table's S#.
    program = source_lines("r4_ps")
    at = program.index("s_load_dwordx4 s[32:35], s[22:23], null")
    words = ["0x91", "0xf00000", "0x4000000", "0"]
    inline = program[:at] + [f"s_mov_b32 s{32 + i}, {w}" for i, w in enumerate(words)] + program[at + 1:]
    _, refs = translate("r4_ps", inline)
    want = [("texture", 0, 0, 0x20), ("inline_sampler", 0, 0x91, 0xf00000, 0x4000000, 0), ("constants", 0, 0, 0x40)]
    if refs != want:
        raise AssertionError(f"r4_ps with an inline sampler: reads {refs}, expected {want}")
    print(f"r4_ps with an inline sampler: translates; reads {refs}")
    for name, line, replacement, reason in REFUSED:
        program = source_lines(name)
        at = program.index(line)
        changed = program[:at] + replacement + program[at + 1:]
        try:
            translate(name, changed)
        except ValueError as error:
            if reason not in str(error):
                raise AssertionError(f"{name} with {replacement}: refused for another reason: {error}")
            print(f"{name} with {replacement[0]!r}: refused as expected: {error}")
        else:
            raise AssertionError(f"{name} with {replacement}: translated")
    if not assembler:
        print("llvm-mc not given: committed bytes and LLVM text comparison skipped")
        return 0
    with tempfile.TemporaryDirectory() as tmp:
        for name, code in programs.items():
            if assemble(assembler, objcopy, source_lines(name), Path(tmp)) != code:
                raise AssertionError(f"{name}: r4_programs.h differs from llvm-mc's assembly; regenerate it")
            if llvm_text(assembler, code) != source_lines(name):
                raise AssertionError(f"{name}: llvm-mc disassembles {llvm_text(assembler, code)}")
        for line in FORMS:
            code = assemble(assembler, objcopy, [line], Path(tmp))
            ours = [text for _, text in gfx_text.decode(code)]
            if ours != llvm_text(assembler, code) or ours != [line]:
                raise AssertionError(f"{line!r}: gfx_text.py {ours} != llvm-mc {llvm_text(assembler, code)}")
    print(f"llvm-mc agrees: {len(programs)} programs, {len(FORMS)} forms")
    return 0


if __name__ == "__main__":
    mode, *args = sys.argv[1:]
    if mode == "header":
        write_header(*args)
        sys.exit(0)
    sys.exit(check(*args))
