"""The gfx1013 program of the runtime pixel input layout (tests/runtime/psin_ps.s, psin_scene.cpp).

    psin_programs_check.py check [<llvm-mc> <llvm-objcopy>]
    psin_programs_check.py header <llvm-mc> <llvm-objcopy> <psin_programs.h>

As tests/runtime/r3_programs_check.py does for R3: the committed bytes in psin_programs.h, decoded by tools/gfx_text.py,
must give the source text line for line. The translator must accept the program under the entry contract the shim
derives from psin_scene.cpp's version 2 container (roles with "ps_input_ena", the X2WShaderPixelInfo record), with
SV_Position and SV_IsFrontFace in the HLSL, and must refuse it under the contracts of the scene's two controls: a
version 1 container (no record: persp_center alone, so v2 is unset) and a record whose ADDR also reserves pos_w (v5
is then pos_w, which ENA does not load). The roles the shim derives for a container without a record must not mention
the input layout (their keys are unchanged). Given llvm-mc, the committed bytes must be what it assembles (llvm-mc 15)
and its disassembly must equal gfx_text.py's text.
"""
from pathlib import Path
import re
import sys
import tempfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(HERE))
import gfx_text  # noqa: E402
import pso_translate  # noqa: E402
from r3_programs_check import assemble, llvm_text  # noqa: E402

PROGRAMS = {"psin_ps": "psin_ps.s"}
# SPI_PS_INPUT_ENA of psin_scene.cpp's container: persp_center | pos_x | pos_y | pos_z | front_face.
ENA = 0x1702
POS_W = 1 << 11
# The roles d3d12_xs::pipeline derives (translate_graphics): no entry SGPRs; the layout only when not the default.
ROLES = {"sgprs": {}, "ps_input_ena": ENA}
REFUSED = [
    ({"sgprs": {}}, "Read of unset vector register v2"),
    ({"sgprs": {}, "ps_input_ena": ENA, "ps_input_addr": ENA | POS_W}, "Read of input VGPR v5 (pos_w)"),
    ({"sgprs": {}, "ps_input_ena": 1 << 8}, "SPI_PS_INPUT_ENA needs a barycentric input"),
    ({"sgprs": {}, "ps_input_ena": "0x1702"}, "ps_input_ena must be an integer"),
]


def source_lines(name):
    lines = [line.split(";")[0].strip() for line in (HERE / PROGRAMS[name]).read_text(encoding="ascii").splitlines()]
    return [" ".join(line.split()) for line in lines if line]


def committed():
    text = (HERE / "psin_programs.h").read_text(encoding="ascii")
    out = {}
    for name in PROGRAMS:
        m = re.search(rf"{name}\[\] = \{{([^}}]*)\}};", text)
        if not m:
            raise AssertionError(f"psin_programs.h lacks {name}")
        out[name] = bytes(int(b, 16) for b in re.findall(r"0x([0-9a-f]{2})", m[1]))
    return out


def write_header(assembler, objcopy, path):
    with tempfile.TemporaryDirectory() as tmp:
        lines = ["// Generated by tests/runtime/psin_programs_check.py header (llvm-mc 15, -mcpu=gfx1013) from",
                 "// tests/runtime/psin_ps.s. Do not edit.", "#pragma once", "#include <cstdint>", ""]
        for name in PROGRAMS:
            code = assemble(assembler, objcopy, source_lines(name), Path(tmp))
            words = ", ".join(f"0x{b:02x}" for b in code)
            lines.append(f"inline constexpr std::uint8_t {name}[] = {{{words}}};")
        Path(path).write_text("\n".join(lines) + "\n", encoding="ascii")


def translate(program, roles):
    source, layout, refs = pso_translate.lower("pixel", program, roles)
    return pso_translate.place_in_runtime_spaces(source, "pixel", layout), refs


def check(assembler=None, objcopy=None):
    import pixel_aot
    code = committed()["psin_ps"]
    decoded = [text for _, text in gfx_text.decode(code)]
    if decoded != source_lines("psin_ps"):
        raise AssertionError("psin_ps: gfx_text.py decodes\n" + "\n".join(decoded))
    program = pixel_aot.name_branch_targets(gfx_text.decode(code), len(code))
    source, refs = translate(program, ROLES)
    for needed in ("float4 frag_position : SV_Position", "bool front_face : SV_IsFrontFace",
                   "uint psin_x = asuint(frag_position.x);", "uint psin_z = asuint(frag_position.z);",
                   "front_face ? 0x3f800000u : 0xbf800000u"):
        if needed not in source:
            raise AssertionError(f"psin_ps: the HLSL lacks {needed!r}")
    if refs or "RootSignature" in source:
        raise AssertionError(f"psin_ps: unexpected bindings {refs}")
    # The path the translator service and tools/precompile_cache.py take (pso_cache.Translator: pso_translate.translate
    # with the roles text the shim recorded) gives the same HLSL.
    import json
    through, _, _, _ = pso_translate.translate("pixel", None, json.loads(json.dumps(ROLES)), instructions=program)
    if through != source:
        raise AssertionError("psin_ps: pso_translate.translate differs from lower + place_in_runtime_spaces")
    print(f"psin_ps: {len(program)} instructions decode to the source text and translate with ENA 0x{ENA:04x}")
    for roles, reason in REFUSED:
        try:
            translate(program, roles)
        except ValueError as error:
            if reason not in str(error):
                raise AssertionError(f"roles {roles}: refused for another reason: {error}")
            print(f"roles {roles}: refused as expected: {error}")
        else:
            raise AssertionError(f"roles {roles}: translated")
    # The shim writes the layout into the roles only when it is not the default (src/d3d12_xs_pipeline.cpp,
    # translate_graphics), so the roles of a pixel container without a record are what they were.
    shim = (ROOT / "src" / "d3d12_xs_pipeline.cpp").read_text(encoding="utf-8")
    if "ps.ps_input_ena != 2 || ps.ps_input_addr != 2" not in shim:
        raise AssertionError("d3d12_xs_pipeline.cpp no longer keeps the default layout out of the roles")
    if not assembler:
        print("llvm-mc not given: committed bytes and LLVM text comparison skipped")
        return 0
    with tempfile.TemporaryDirectory() as tmp:
        if assemble(assembler, objcopy, source_lines("psin_ps"), Path(tmp)) != code:
            raise AssertionError("psin_ps: psin_programs.h differs from llvm-mc's assembly; regenerate it")
        if llvm_text(assembler, code) != source_lines("psin_ps"):
            raise AssertionError(f"psin_ps: llvm-mc disassembles {llvm_text(assembler, code)}")
    print("llvm-mc agrees: 1 program")
    return 0


if __name__ == "__main__":
    if len(sys.argv) >= 2 and sys.argv[1] == "check":
        sys.exit(check(*sys.argv[2:4]))
    if len(sys.argv) == 5 and sys.argv[1] == "header":
        write_header(sys.argv[2], sys.argv[3], sys.argv[4])
        sys.exit(0)
    print(__doc__)
    sys.exit(2)
