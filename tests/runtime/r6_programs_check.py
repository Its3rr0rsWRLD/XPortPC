"""The gfx1013 programs of runtime rung R6 (tests/runtime/r6_*.s): hardware descriptor words in title heaps.

    r6_programs_check.py check [<llvm-mc> <llvm-objcopy>]
    r6_programs_check.py header <llvm-mc> <llvm-objcopy> <r6_programs.h>

As tests/runtime/r4_programs_check.py does for R4: the committed bytes in r6_programs.h, decoded by tools/gfx_text.py,
must give the source text line for line; the translator must accept both programs under the entry contracts the shim
derives from r6_rawdesc_scene.cpp's and r6_rawdesc_compute.cpp's containers and report the reads their tables are laid
out for (the inline sampler with its four S# words; the compute program's buffer V# as frame words 60..63, its T# as
texture slot 0 and its S# as sampler slot 0), and the HLSL must bind only what the shim fills. Forms the runtime does
not bind in a compute program are refused with their reason. Given llvm-mc, the committed bytes must be what it
assembles (llvm-mc 15) and its disassembly must equal gfx_text.py's text, for the programs and for FORMS.
"""
from pathlib import Path
import re
import sys
import tempfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(HERE))
import gfx_text  # noqa: E402
import pso_translate  # noqa: E402
from r3_programs_check import assemble, llvm_text  # noqa: E402

PROGRAMS = {"r6_ps_inline": "r6_ps_inline.s", "r6_cs": "r6_cs.s"}
# r6_rawdesc_scene.cpp: the r4_vs/r4_ps pipeline, and the inline-sampler pipeline r4_vs + r6_ps_inline, whose
# vertex root words are push words 0..3 and whose pixel s5 is push word 4. r6_rawdesc_compute.cpp: s2 and s3 are
# descriptor sets 0 and 1, s4 the first push word; workgroup 8x8x1, wave32, two local-id VGPRs.
PS_ROLES = {"sgprs": {"s2": "interp", "s3": "descriptors", "s5": "push:4"}}
CS_ROLES = {"sgprs": {"s2": "descriptors", "s3": "descriptors.1", "s4": "user:0"}, "numthreads": [8, 8, 1],
            "wave": 32, "local_ids": 2}
EXPECTED = {
    "r6_ps_inline": [("texture", 0, 0, 0x20), ("inline_sampler", 0, 0x91, 0xf00000, 0x4000000, 0),
                     ("constants", 0, 0, 0x40)],
    "r6_cs": [("buffer", 60, 0, 0x20), ("texture", 0, 0, 0), ("sampler", 0, 1, 0)],
}
REGISTERS = {
    "r6_ps_inline": ["register(b0, space1003)", "register(b3, space1000)", "register(s0, space1002)",
                     "register(t0, space1002)"],
    "r6_cs": ["register(b3, space1000)", "register(s0, space1002)", "register(t0, space1002)",
              "register(t2, space1000)", "register(u0, space1000)", "register(u0, space1001)"],
}
# Compute forms the runtime does not bind from a table, as one-line changes of r6_cs, and the reason they give.
REFUSED = [
    ("r6_cs", "s_endpgm", ["s_load_dwordx4 s[40:43], s[20:21], 0x40", "s_waitcnt lgkmcnt(0)",
                           "s_buffer_load_dword s44, s[40:43], null", "s_endpgm"], "constant-buffer V#"),
    ("r6_cs", "s_endpgm", ["s_load_dwordx8 s[40:47], s[20:21], 0x40", "s_waitcnt lgkmcnt(0)",
                           "image_store v[4:7], v[0:1], s[40:47] dmask:0xf dim:SQ_RSRC_IMG_2D unorm", "s_endpgm"],
     "storage image"),
]
FORMS = [
    "image_load v[4:7], v[0:1], s[24:31] dmask:0xf dim:SQ_RSRC_IMG_2D unorm",
    "image_load v[4:5], v[0:1], s[24:31] dmask:0x3 dim:SQ_RSRC_IMG_2D unorm",
    "image_sample_lz v[8:11], v[2:3], s[24:31], s[36:39] dmask:0xf dim:SQ_RSRC_IMG_2D",
    "v_cvt_f32_u32_e32 v2, v0", "v_cvt_f32_u32_e32 v3, s4",
    "v_mul_f32_e32 v2, 0x3e000000, v2", "s_mov_b32 s32, 0x91", "s_mov_b32 s34, 0x4000000",
    "buffer_store_dwordx4 v[8:11], v12, s[32:35], 0 offen offset:16",
]


def source_lines(name):
    lines = [line.split(";")[0].strip() for line in (HERE / PROGRAMS[name]).read_text(encoding="ascii").splitlines()]
    return [" ".join(line.split()) for line in lines if line]


def committed():
    text = (HERE / "r6_programs.h").read_text(encoding="ascii")
    out = {}
    for name in PROGRAMS:
        m = re.search(rf"{name}\[\] = \{{([^}}]*)\}};", text)
        if not m:
            raise AssertionError(f"r6_programs.h lacks {name}")
        out[name] = bytes(int(b, 16) for b in re.findall(r"0x([0-9a-f]{2})", m[1]))
    return out


def write_header(assembler, objcopy, path):
    with tempfile.TemporaryDirectory() as tmp:
        lines = ["// Generated by tests/runtime/r6_programs_check.py header (llvm-mc 15, -mcpu=gfx1013) from",
                 "// tests/runtime/r6_*.s. Do not edit.", "#pragma once", "#include <cstdint>", ""]
        for name in PROGRAMS:
            code = assemble(assembler, objcopy, source_lines(name), Path(tmp))
            words = ", ".join(f"0x{b:02x}" for b in code)
            lines.append(f"inline constexpr std::uint8_t {name}[] = {{{words}}};")
        Path(path).write_text("\n".join(lines) + "\n", encoding="ascii")


def translate(name, program):
    stage = "compute" if name.endswith("_cs") else "pixel"
    source, layout, refs = pso_translate.lower(stage, program, CS_ROLES if stage == "compute" else PS_ROLES)
    return pso_translate.place_in_runtime_spaces(source, stage, layout), refs


def check(assembler=None, objcopy=None):
    import pixel_aot
    programs = committed()
    for name, code in programs.items():
        decoded = [text for _, text in gfx_text.decode(code)]
        if decoded != source_lines(name):
            raise AssertionError(f"{name}: gfx_text.py decodes\n" + "\n".join(decoded))
        program = pixel_aot.name_branch_targets(gfx_text.decode(code), len(code))
        source, refs = translate(name, program)
        if refs != EXPECTED[name]:
            raise AssertionError(f"{name}: descriptor-table reads {refs}, expected {EXPECTED[name]}")
        registers = sorted(set(re.findall(r"register\([^)]*\)", source)))
        if registers != REGISTERS[name] or "RootSignature" in source:
            raise AssertionError(f"{name}: unexpected bindings {registers}")
        if "cbuffer X2WFrame : register(b3, space1000)" not in source:
            raise AssertionError(f"{name}: the push words are not the frame words")
        print(f"{name}: {len(program)} instructions decode to the source text and translate; reads {refs}")
    for name, line, replacement, reason in REFUSED:
        program = source_lines(name)
        at = program.index(line)
        changed = program[:at] + replacement + program[at + 1:]
        try:
            translate(name, changed)
        except ValueError as error:
            if reason not in str(error):
                raise AssertionError(f"{name} with {replacement}: refused for another reason: {error}")
            print(f"{name} with {replacement[0]!r}: refused as expected: {error}")
        else:
            raise AssertionError(f"{name} with {replacement}: translated")
    if not assembler:
        print("llvm-mc not given: committed bytes and LLVM text comparison skipped")
        return 0
    with tempfile.TemporaryDirectory() as tmp:
        for name, code in programs.items():
            if assemble(assembler, objcopy, source_lines(name), Path(tmp)) != code:
                raise AssertionError(f"{name}: r6_programs.h differs from llvm-mc's assembly; regenerate it")
            if llvm_text(assembler, code) != source_lines(name):
                raise AssertionError(f"{name}: llvm-mc disassembles {llvm_text(assembler, code)}")
        for line in FORMS:
            code = assemble(assembler, objcopy, [line], Path(tmp))
            ours = [text for _, text in gfx_text.decode(code)]
            if ours != llvm_text(assembler, code) or ours != [line]:
                raise AssertionError(f"{line!r}: gfx_text.py {ours} != llvm-mc {llvm_text(assembler, code)}")
    print(f"llvm-mc agrees: {len(programs)} programs, {len(FORMS)} forms")
    return 0


if __name__ == "__main__":
    if len(sys.argv) >= 2 and sys.argv[1] == "check":
        sys.exit(check(*sys.argv[2:4]))
    if len(sys.argv) == 5 and sys.argv[1] == "header":
        write_header(sys.argv[2], sys.argv[3], sys.argv[4])
        sys.exit(0)
    print(__doc__)
    sys.exit(2)
